//! Generates service configs from settings. Files under `etc/` are rewritten before every
//! start, so they always match the active versions and ports.

use std::path::{Path, PathBuf};

use crate::{
    config::Settings,
    error::{Error, Result},
    layout::{Layout, exe},
};

/// Paths in Apache/PHP/MariaDB configs use forward slashes on every OS.
fn slash(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

fn php_home(settings: &Settings, layout: &Layout) -> Option<PathBuf> {
    settings.versions.php.as_ref().map(|v| layout.bin("php", v)).filter(|p| p.exists())
}

pub fn write_apache(settings: &Settings, layout: &Layout) -> Result<()> {
    let version = settings.versions.apache.as_ref().ok_or_else(|| Error::msg("Apache is not installed"))?;
    let home = slash(&layout.bin("apache", version));
    let etc = layout.etc("apache");
    std::fs::create_dir_all(etc.join("sites"))?;
    let www = slash(&layout.www());
    let logs = slash(&layout.logs());
    let port = settings.ports.http;

    let mut modules = vec![
        "access_compat", "actions", "alias", "allowmethods", "auth_basic", "authn_core", "authn_file",
        "authz_core", "authz_groupfile", "authz_host", "authz_user", "autoindex", "deflate", "dir", "env",
        "expires", "filter", "headers", "include", "log_config", "mime", "negotiation", "proxy",
        "proxy_fcgi", "proxy_http", "rewrite", "setenvif", "socache_shmcb", "vhost_alias",
    ];
    if !cfg!(windows) {
        modules.extend(["mpm_event", "unixd"]);
    }
    let modules: String = modules
        .iter()
        .map(|m| format!("LoadModule {m}_module modules/mod_{m}.so\n"))
        .collect();

    let php = match php_home(settings, layout) {
        Some(php) if cfg!(windows) => {
            let module = php.join("php8apache2_4.dll");
            if module.exists() {
                format!(
                    "LoadModule php_module \"{}\"\nPHPIniDir \"{}\"\n<FilesMatch \"\\.php$\">\n    SetHandler application/x-httpd-php\n</FilesMatch>\n",
                    slash(&module),
                    slash(&layout.etc("php")),
                )
            } else {
                "# PHP build has no Apache module (non thread-safe build?)\n".into()
            }
        }
        Some(_) => format!(
            "<FilesMatch \"\\.php$\">\n    SetHandler \"proxy:fcgi://127.0.0.1:{}\"\n</FilesMatch>\n",
            settings.ports.php_fpm
        ),
        None => "# PHP is not installed\n".into(),
    };

    let conf = format!(
        r#"# Generated by lampRabit. Changes are overwritten on every start;
# put custom directives in etc/apache/sites/*.conf instead.

Define SRVROOT "{home}"
ServerRoot "${{SRVROOT}}"
Listen {port}
ServerName localhost:{port}
ServerAdmin admin@localhost

{modules}
<IfModule unixd_module>
    User daemon
    Group daemon
</IfModule>

<Directory />
    AllowOverride none
    Require all denied
</Directory>

DocumentRoot "{www}"
<Directory "{www}">
    Options Indexes FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>

DirectoryIndex index.php index.html index.htm

<Files ".ht*">
    Require all denied
</Files>

ErrorLog "{logs}/apache-error.log"
LogLevel warn
LogFormat "%h %l %u %t \"%r\" %>s %b \"%{{Referer}}i\" \"%{{User-Agent}}i\"" combined
CustomLog "{logs}/apache-access.log" combined

TypesConfig conf/mime.types
AddType application/x-compress .Z
AddType application/x-gzip .gz .tgz

<IfModule mpm_winnt_module>
    AcceptFilter http none
    AcceptFilter https none
    ThreadsPerChild 64
</IfModule>

EnableSendfile off
EnableMMAP off

{php}
IncludeOptional "{sites}/*.conf"
"#,
        sites = slash(&etc.join("sites")),
    );
    std::fs::write(etc.join("httpd.conf"), conf)?;
    Ok(())
}

pub fn write_php(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = php_home(settings, layout).ok_or_else(|| Error::msg("PHP is not installed"))?;
    let etc = layout.etc("php");
    std::fs::create_dir_all(&etc)?;
    let sessions = layout.tmp().join("sessions");
    std::fs::create_dir_all(&sessions)?;

    // Start from PHP's own development defaults, then append overrides (later directives win).
    let mut ini = std::fs::read_to_string(home.join("php.ini-development")).unwrap_or_default();
    let ext_dir = home.join("ext");
    ini.push_str(&format!(
        r#"

; ---------------------------------------------------------------
; lampRabit overrides (regenerated on every start)
; ---------------------------------------------------------------
extension_dir = "{ext}"
memory_limit = 512M
upload_max_filesize = 128M
post_max_size = 128M
max_execution_time = 120
date.timezone = UTC
display_errors = On
log_errors = On
error_log = "{logs}/php-error.log"
session.save_path = "{sessions}"
upload_tmp_dir = "{tmp}"
"#,
        ext = slash(&ext_dir),
        logs = slash(&layout.logs()),
        sessions = slash(&sessions),
        tmp = slash(&layout.tmp()),
    ));

    let extensions = [
        "bz2", "curl", "exif", "fileinfo", "gd", "gettext", "intl", "mbstring", "mysqli", "openssl",
        "pdo_mysql", "pdo_sqlite", "sodium", "sqlite3", "xsl", "zip",
    ];
    for ext in extensions {
        if cfg!(windows) && !ext_dir.join(format!("php_{ext}.dll")).exists() {
            continue; // compiled in, or not shipped with this build
        }
        ini.push_str(&format!("extension={ext}\n"));
    }
    if !cfg!(windows) || ext_dir.join("php_opcache.dll").exists() {
        ini.push_str("zend_extension=opcache\nopcache.enable=1\nopcache.validate_timestamps=1\nopcache.revalidate_freq=0\n");
    }
    std::fs::write(etc.join("php.ini"), ini)?;

    if !cfg!(windows) {
        let fpm = format!(
            "[global]\nerror_log = {logs}/php-fpm.log\n\n[www]\nlisten = 127.0.0.1:{port}\npm = dynamic\npm.max_children = 10\npm.start_servers = 2\npm.min_spare_servers = 1\npm.max_spare_servers = 4\n",
            logs = slash(&layout.logs()),
            port = settings.ports.php_fpm,
        );
        std::fs::write(etc.join("php-fpm.conf"), fpm)?;
    }
    Ok(())
}

pub fn mariadb_home(settings: &Settings, layout: &Layout) -> Result<PathBuf> {
    let version = settings.versions.mariadb.as_ref().ok_or_else(|| Error::msg("MariaDB is not installed"))?;
    Ok(layout.bin("mariadb", version))
}

pub fn write_mariadb(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = mariadb_home(settings, layout)?;
    let etc = layout.etc("mariadb");
    std::fs::create_dir_all(&etc)?;
    let port = settings.ports.mysql;
    let socket = if cfg!(windows) {
        String::new()
    } else {
        format!("socket=\"{}\"\n", slash(&layout.tmp().join("mysql.sock")))
    };
    let conf = format!(
        r#"# Generated by lampRabit. Changes are overwritten on every start.
[mysqld]
basedir="{home}"
datadir="{data}"
port={port}
bind-address=127.0.0.1
{socket}character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
log-error="{logs}/mariadb-error.log"
max_allowed_packet=64M
innodb_buffer_pool_size=256M

[client]
port={port}
{socket}default-character-set=utf8mb4
"#,
        home = slash(&home),
        data = slash(&layout.data("mariadb")),
        logs = slash(&layout.logs()),
    );
    std::fs::write(etc.join("my.ini"), conf)?;
    Ok(())
}

/// Creates the system tables on first start. Root gets an empty password, like XAMPP/Laragon.
pub async fn init_mariadb_data(settings: &Settings, layout: &Layout) -> Result<()> {
    let data = layout.data("mariadb");
    if data.join("mysql").exists() {
        return Ok(());
    }
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        return Err(Error::msg(format!(
            "{} is not empty but has no MariaDB system tables; move it away to re-initialise",
            data.display()
        )));
    }
    std::fs::create_dir_all(&data)?;
    let home = mariadb_home(settings, layout)?;

    let mut cmd = if cfg!(windows) {
        let mut c = tokio::process::Command::new(home.join("bin").join(exe("mariadb-install-db")));
        c.arg(format!("--datadir={}", data.display()));
        c
    } else {
        let mut c = tokio::process::Command::new(home.join("scripts").join("mariadb-install-db"));
        c.args([
            "--no-defaults".to_string(),
            format!("--basedir={}", home.display()),
            format!("--datadir={}", data.display()),
            "--auth-root-authentication-method=normal".to_string(),
        ]);
        c
    };
    cmd.current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    if !out.status.success() {
        let _ = std::fs::remove_dir_all(&data);
        return Err(Error::msg(format!(
            "MariaDB data directory initialisation failed: {}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}
