//! Generates service configs from settings. Files under `etc/` are rewritten before every
//! start, so they always match the active versions and ports.

use std::path::{Path, PathBuf};

use crate::{
    config::{Database, Server, Settings},
    php::PoolPlan,
    error::{Error, Result},
    layout::{Layout, exe},
};

/// Paths in Apache/PHP/MariaDB configs use forward slashes on every OS.
fn slash(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

pub fn write_apache(settings: &Settings, layout: &Layout, plan: &[PoolPlan]) -> Result<()> {
    let version = settings.versions.apache.as_ref().ok_or_else(|| Error::msg("Apache is not installed"))?;
    let home = slash(&layout.bin("apache", version));
    let etc = layout.etc("apache");
    std::fs::create_dir_all(etc.join("sites"))?;
    let www = slash(&layout.www());
    let logs = slash(&layout.logs());
    let port = settings.server_ports(Server::Apache).0;
    let runtime_dir = layout.tmp().join("apache");
    std::fs::create_dir_all(&runtime_dir)?;

    let mut modules = vec![
        "access_compat", "actions", "alias", "allowmethods", "auth_basic", "authn_core", "authn_file",
        "authz_core", "authz_groupfile", "authz_host", "authz_user", "autoindex", "deflate", "dir", "env",
        "expires", "filter", "headers", "include", "lbmethod_byrequests", "log_config", "mime", "negotiation",
        "proxy", "proxy_balancer", "proxy_fcgi", "proxy_http", "rewrite", "setenvif", "slotmem_shm",
        "socache_shmcb", "vhost_alias",
    ];
    if !cfg!(windows) {
        modules.extend(["mpm_event", "unixd"]);
    }
    let modules: String = modules
        .iter()
        .map(|m| format!("LoadModule {m}_module modules/mod_{m}.so\n"))
        .collect();

    // PHP runs in FastCGI worker pools (see php.rs); one balancer per PHP version in use.
    let balancers: String = plan
        .iter()
        .map(|p| {
            let members: String = p.ports().map(|port| format!("    BalancerMember \"fcgi://127.0.0.1:{port}\"\n")).collect();
            format!("<Proxy \"balancer://{}/\">\n{members}</Proxy>\n", p.name())
        })
        .collect();
    let php = if plan.is_empty() {
        "# PHP is not installed\n".to_string()
    } else {
        // GENERIC passes SCRIPT_FILENAME as a plain path; on Windows it arrives as
        // "/C:/...", so strip the slash before the drive letter.
        format!(
            "ProxyFCGIBackendType GENERIC\nProxyFCGISetEnvIf \"reqenv('SCRIPT_FILENAME') =~ m#^/([A-Za-z]:/.*)#\" SCRIPT_FILENAME \"$1\"\n{balancers}{default}",
            default = crate::sites::apache_php_handler(crate::php::pool_for(plan, None, settings), ""),
        )
    };

    let conf = format!(
        r#"# Generated by LampRabit. Changes are overwritten on every start;
# put custom directives in etc/apache/sites/*.conf instead.

Define SRVROOT "{home}"
ServerRoot "${{SRVROOT}}"
Listen {port}
ServerName localhost:{port}
ServerAdmin admin@localhost

{modules}
<IfModule unixd_module>
    User daemon
    Group daemon
</IfModule>

<Directory />
    AllowOverride none
    Require all denied
</Directory>

DocumentRoot "{www}"
<Directory "{www}">
    Options Indexes FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>

DirectoryIndex index.php index.html index.htm

<Files ".ht*">
    Require all denied
</Files>

DefaultRuntimeDir "{runtime}"
PidFile "{pidfile}"
ErrorLog "{logs}/apache-error.log"
LogLevel warn
LogFormat "%h %l %u %t \"%r\" %>s %b \"%{{Referer}}i\" \"%{{User-Agent}}i\"" combined
# LampRabit's own health checks would otherwise add a line every few seconds.
SetEnvIf User-Agent "^lampRabit/" lamprabit_probe
CustomLog "{logs}/apache-access.log" combined env=!lamprabit_probe

TypesConfig conf/mime.types
AddType application/x-compress .Z
AddType application/x-gzip .gz .tgz

<IfModule mpm_winnt_module>
    AcceptFilter http none
    AcceptFilter https none
    ThreadsPerChild 64
</IfModule>

EnableSendfile off
EnableMMAP off

{php}
# Virtual hosts for the folders in www/
Include "{vhosts}"
IncludeOptional "{sites}/*.conf"
"#,
        sites = slash(&etc.join("sites")),
        vhosts = slash(&crate::sites::config_path(layout, Server::Apache)),
        runtime = slash(&runtime_dir),
        pidfile = slash(&apache_pid_file(layout)),
    );
    std::fs::write(etc.join("httpd.conf"), conf)?;
    Ok(())
}

/// LampRabit stops Apache by ending its process tree, so a stale PID file is expected and
/// removed before each start rather than letting Apache warn about an unclean shutdown.
pub fn apache_pid_file(layout: &Layout) -> PathBuf {
    layout.tmp().join("httpd.pid")
}

/// Sends PHP's mail() to Mailpit. Windows PHP speaks SMTP itself; elsewhere mail() pipes
/// to a sendmail binary, and `mailpit sendmail` is a drop-in one.
fn mail_directives(settings: &Settings, layout: &Layout) -> String {
    let Some(version) = settings.versions.mailpit.as_ref().filter(|_| settings.route_mail) else {
        return String::new();
    };
    let port = settings.ports.mail_smtp;
    if cfg!(windows) {
        format!("\n; mail() goes to Mailpit\nSMTP = 127.0.0.1\nsmtp_port = {port}\nsendmail_from = \"lamprabit@localhost\"\n")
    } else {
        let mailpit = slash(&layout.bin("mailpit", version).join("mailpit"));
        format!("\n; mail() goes to Mailpit\nsendmail_path = \"{mailpit} sendmail -S 127.0.0.1:{port}\"\n")
    }
}

/// Glue files for the database tools: Adminer's login wrapper and phpMyAdmin's config.
/// The installed databases as (label, "host:port"), the default first, for the web tools.
fn tool_servers(settings: &Settings) -> Vec<(String, String)> {
    settings
        .databases()
        .into_iter()
        .map(|db| {
            let version = settings.database_version(db).map(String::as_str).unwrap_or_default();
            (format!("{} {version}", db.label()), format!("127.0.0.1:{}", settings.database_port(db)))
        })
        .collect()
}

pub fn write_tools(settings: &Settings, layout: &Layout) -> Result<()> {
    let servers = tool_servers(settings);
    let php_str = |s: &str| format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'"));
    if let Some(version) = &settings.versions.adminer {
        let default = servers.first().map_or_else(|| "127.0.0.1:3306".to_string(), |(_, addr)| addr.clone());
        let options: String = servers
            .iter()
            .map(|(label, addr)| format!("{} => {}, ", php_str(addr), php_str(label)))
            .collect();
        // Adminer refuses empty passwords by default (local root has none) and asks for a
        // free-text server; this offers the installed databases instead.
        let wrapper = format!(
            r#"<?php
// Generated by LampRabit; regenerated on every web server start.
function adminer_object() {{
    class LampRabitAdminer extends \Adminer\Adminer {{
        function login($login, $password) {{
            return true;
        }}
        function credentials() {{
            return array(\Adminer\SERVER !== '' ? \Adminer\SERVER : {default}, $_GET['username'] ?? 'root', \Adminer\get_password());
        }}
        function loginFormField($name, $heading, $value) {{
            $servers = array({options});
            if ($name == 'server' && count($servers) > 0) {{
                $current = \Adminer\SERVER !== '' ? \Adminer\SERVER : {default};
                $select = '<select name="auth[server]">';
                foreach ($servers as $address => $label) {{
                    $select .= '<option value="' . \Adminer\h($address) . '"' . ($address == $current ? ' selected' : '') . '>' . \Adminer\h($label) . '</option>';
                }}
                return $heading . $select . "</select>\n";
            }}
            return parent::loginFormField($name, $heading, $value);
        }}
    }}
    return new LampRabitAdminer;
}}
include __DIR__ . '/adminer.php';
"#,
            default = php_str(&default),
        );
        std::fs::write(layout.bin("adminer", version).join("index.php"), wrapper)?;
    }

    if let Some(version) = &settings.versions.phpmyadmin {
        let tmp = layout.tmp().join("phpmyadmin");
        std::fs::create_dir_all(&tmp)?;
        // One server per installed database, the default first; the login page offers a
        // choice when there are two (and ?server=2 opens the second directly).
        let mut entries: String = servers
            .iter()
            .map(|(label, addr)| {
                let (host, port) = addr.split_once(':').unwrap_or((addr.as_str(), "3306"));
                format!(
                    "$i++;\n$cfg['Servers'][$i]['verbose'] = {};\n$cfg['Servers'][$i]['host'] = {};\n$cfg['Servers'][$i]['port'] = {};\n$cfg['Servers'][$i]['auth_type'] = 'cookie';\n$cfg['Servers'][$i]['AllowNoPassword'] = true;\n",
                    php_str(label),
                    php_str(host),
                    php_str(port),
                )
            })
            .collect();
        if entries.is_empty() {
            entries = "$i++;\n$cfg['Servers'][$i]['host'] = '127.0.0.1';\n$cfg['Servers'][$i]['auth_type'] = 'cookie';\n$cfg['Servers'][$i]['AllowNoPassword'] = true;\n".into();
        }
        let config = format!(
            r#"<?php
// Generated by LampRabit; regenerated on every web server start.
$cfg['blowfish_secret'] = '{secret}';
$i = 0;
{entries}$cfg['ServerDefault'] = 1;
$cfg['TempDir'] = '{tmp}';
$cfg['VersionCheck'] = false;
"#,
            secret = phpmyadmin_secret(layout)?,
            tmp = slash(&tmp),
        );
        let dir = layout.bin("phpmyadmin", version);
        std::fs::write(dir.join("config.inc.php"), config)?;
        // phpMyAdmin lags behind new PHP releases; keep deprecation notices off its pages.
        std::fs::write(dir.join(".user.ini"), "display_errors = Off\n")?;
    }
    write_phpredisadmin(settings, layout)?;
    Ok(())
}

/// phpRedisAdmin's config: LampRabit's Redis, no login (it's only reachable from this
/// machine). Written on every web server start, so a port change is picked up.
fn write_phpredisadmin(settings: &Settings, layout: &Layout) -> Result<()> {
    let Some(version) = &settings.versions.phpredisadmin else { return Ok(()) };
    let config = format!(
        r#"<?php
// Generated by LampRabit; regenerated on every web server start.
$config = array(
    'servers' => array(
        array('name' => 'LampRabit Redis', 'host' => '127.0.0.1', 'port' => {port}, 'filter' => '*', 'scheme' => 'tcp'),
    ),
    'seperator' => ':',
    'showEmptyNamespaceAsKey' => false,
    'hideEmptyDBs' => false,
    'maxkeylen' => 100,
    'count_elements_page' => 100,
    'keys' => false,
    'scansize' => 1000,
    // Only reachable from this machine; phpRedisAdmin otherwise insists on a login.
    'allow_no_auth' => true,
);
"#,
        port = settings.ports.redis,
    );
    let home = layout.bin("phpredisadmin", version);
    std::fs::write(home.join("includes").join("config.inc.php"), config)?;
    Ok(())
}

/// phpMyAdmin encrypts its login cookie with this; kept stable so logins survive restarts.
fn phpmyadmin_secret(layout: &Layout) -> Result<String> {
    use std::hash::{BuildHasher, Hasher};
    let path = layout.etc("phpmyadmin").join("blowfish_secret");
    if let Ok(secret) = std::fs::read_to_string(&path) {
        if secret.trim().len() == 32 {
            return Ok(secret.trim().to_string());
        }
    }
    // RandomState is seeded from the OS RNG; two hashers give 32 hex characters.
    let secret: String = (0..2)
        .map(|_| format!("{:016x}", std::collections::hash_map::RandomState::new().build_hasher().finish()))
        .collect();
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(&path, &secret)?;
    Ok(secret)
}

/// Writes etc/php/<version>/php.ini (and php-fpm.conf outside Windows); returns the ini path.
pub fn write_php(settings: &Settings, layout: &Layout, version: &str, port: u16) -> Result<PathBuf> {
    let home = layout.bin("php", version);
    if !home.exists() {
        return Err(Error::msg(format!("PHP {version} is not installed")));
    }
    let etc = layout.etc("php").join(version);
    std::fs::create_dir_all(&etc)?;
    let sessions = layout.tmp().join("sessions");
    std::fs::create_dir_all(&sessions)?;

    // Start from PHP's own development defaults, then append overrides (later directives win).
    let mut ini = std::fs::read_to_string(home.join("php.ini-development")).unwrap_or_default();
    let ext_dir = home.join("ext");
    ini.push_str(&format!(
        r#"

; ---------------------------------------------------------------
; LampRabit overrides (regenerated on every start)
; ---------------------------------------------------------------
extension_dir = "{ext}"
memory_limit = 512M
upload_max_filesize = 128M
post_max_size = 128M
max_execution_time = 120
date.timezone = UTC
display_errors = On
log_errors = On
error_log = "{logs}/php-error.log"
session.save_path = "{sessions}"
upload_tmp_dir = "{tmp}"
"#,
        ext = slash(&ext_dir),
        logs = slash(&layout.logs()),
        sessions = slash(&sessions),
        tmp = slash(&layout.tmp()),
    ));

    ini.push_str("
; Extensions (Services → PHP → Extensions)
");
    ini.push_str(&crate::extensions::ini_lines(settings, layout, version));
    ini.push_str(&mail_directives(settings, layout));
    let ini_path = etc.join("php.ini");
    std::fs::write(&ini_path, ini)?;

    if !cfg!(windows) {
        let fpm = format!(
            "[global]\nerror_log = {logs}/php-fpm.log\n\n[www]\nlisten = 127.0.0.1:{port}\npm = dynamic\npm.max_children = 10\npm.start_servers = 2\npm.min_spare_servers = 1\npm.max_spare_servers = 4\n",
            logs = slash(&layout.logs()),
        );
        std::fs::write(etc.join("php-fpm.conf"), fpm)?;
    }
    Ok(ini_path)
}

pub fn mariadb_home(settings: &Settings, layout: &Layout) -> Result<PathBuf> {
    let version = settings.versions.mariadb.as_ref().ok_or_else(|| Error::msg("MariaDB is not installed"))?;
    Ok(layout.bin("mariadb", version))
}

pub fn write_mariadb(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = mariadb_home(settings, layout)?;
    let etc = layout.etc("mariadb");
    std::fs::create_dir_all(&etc)?;
    let port = settings.ports.mysql;
    let bind = bind_addresses(settings.versions.mariadb.as_deref().is_some_and(|v| release_line(v) >= (10, 11)));
    let socket = if cfg!(windows) {
        String::new()
    } else {
        format!("socket=\"{}\"\n", slash(&layout.tmp().join("mysql.sock")))
    };
    let conf = format!(
        r#"# Generated by LampRabit. Changes are overwritten on every start.
[mysqld]
basedir="{home}"
datadir="{data}"
port={port}
bind-address={bind}
{socket}character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
log-error="{logs}/mariadb-error.log"
max_allowed_packet=64M
# Level 1 keeps real warnings but not "Aborted connection" notes from health checks.
log_warnings=1
innodb_buffer_pool_size=256M

[client]
port={port}
{socket}default-character-set=utf8mb4
"#,
        home = slash(&home),
        data = slash(&layout.data("mariadb")),
        logs = slash(&layout.logs()),
    );
    std::fs::write(etc.join("my.ini"), conf)?;
    Ok(())
}

fn mariadb_marker(layout: &Layout) -> PathBuf {
    layout.data("mariadb").join("lamprabit-version")
}

/// The database's listening addresses: IPv4 and IPv6 loopback where the server accepts a
/// list (MySQL 8.0.13+, MariaDB 10.11+) and the machine has IPv6. "localhost" often
/// resolves to ::1 first (Windows does), so a server on 127.0.0.1 alone refuses clients
/// configured with "localhost" depending on which address they try. Never all interfaces:
/// root has no password.
fn bind_addresses(accepts_list: bool) -> &'static str {
    if accepts_list && std::net::TcpListener::bind("[::1]:0").is_ok() { "127.0.0.1,::1" } else { "127.0.0.1" }
}

fn release_line(version: &str) -> (u32, u32) {
    let mut parts = version.split('.').map(|p| p.parse().unwrap_or(0));
    (parts.next().unwrap_or(0), parts.next().unwrap_or(0))
}

/// Guards the data directory against version switches. Returns the previous version when
/// the data comes from an older release line and needs `mariadb-upgrade` after start;
/// refuses to start an older MariaDB on newer data, which can damage it.
pub fn mariadb_version_guard(settings: &Settings, layout: &Layout) -> Result<Option<String>> {
    let Some(current) = settings.versions.mariadb.clone() else { return Ok(None) };
    if !layout.data("mariadb").join("mysql").exists() {
        return Ok(None); // fresh data directory; marked after initialisation
    }
    let Ok(previous) = std::fs::read_to_string(mariadb_marker(layout)).map(|s| s.trim().to_string()) else {
        // Data from before LampRabit tracked versions: assume it matches.
        write_mariadb_marker(settings, layout);
        return Ok(None);
    };
    match release_line(&previous).cmp(&release_line(&current)) {
        std::cmp::Ordering::Greater => Err(Error::msg(format!(
            "The database files were last used by MariaDB {previous}. Starting the older {current} on them isn't supported and can damage data. Switch back to {previous} (Services → MariaDB), or move data/mariadb aside to start with an empty database."
        ))),
        std::cmp::Ordering::Less => Ok(Some(previous)),
        std::cmp::Ordering::Equal => {
            if previous != current {
                write_mariadb_marker(settings, layout); // patch release: nothing to upgrade
            }
            Ok(None)
        }
    }
}

pub fn mariadb_marker_exists(layout: &Layout) -> bool {
    mariadb_marker(layout).exists()
}

pub fn write_mariadb_marker(settings: &Settings, layout: &Layout) {
    if let Some(v) = &settings.versions.mariadb {
        let _ = std::fs::write(mariadb_marker(layout), v);
    }
}

/// Upgrades system tables after moving to a newer MariaDB release line.
pub async fn mariadb_upgrade(settings: &Settings, layout: &Layout) -> Result<String> {
    let home = mariadb_home(settings, layout)?;
    let mut cmd = tokio::process::Command::new(home.join("bin").join(exe("mariadb-upgrade")));
    cmd.arg(format!("--defaults-file={}", layout.etc("mariadb").join("my.ini").display())).arg("--user=root").current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    if out.status.success() {
        write_mariadb_marker(settings, layout);
        Ok(text)
    } else {
        Err(Error::msg(format!("mariadb-upgrade failed: {}", text.lines().last().unwrap_or_default())))
    }
}

/// Creates the system tables on first start. Root gets an empty password, like XAMPP/Laragon.
pub async fn init_mariadb_data(settings: &Settings, layout: &Layout) -> Result<()> {
    let data = layout.data("mariadb");
    if data.join("mysql").exists() {
        return Ok(());
    }
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        return Err(Error::msg(format!(
            "{} is not empty but has no MariaDB system tables; move it away to re-initialise",
            data.display()
        )));
    }
    std::fs::create_dir_all(&data)?;
    let home = mariadb_home(settings, layout)?;

    let mut cmd = if cfg!(windows) {
        let mut c = tokio::process::Command::new(home.join("bin").join(exe("mariadb-install-db")));
        c.arg(format!("--datadir={}", data.display()));
        c
    } else {
        let mut c = tokio::process::Command::new(home.join("scripts").join("mariadb-install-db"));
        c.args([
            "--no-defaults".to_string(),
            format!("--basedir={}", home.display()),
            format!("--datadir={}", data.display()),
            "--auth-root-authentication-method=normal".to_string(),
        ]);
        c
    };
    cmd.current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    if !out.status.success() {
        let _ = std::fs::remove_dir_all(&data);
        return Err(Error::msg(format!(
            "MariaDB data directory initialisation failed: {}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}

pub fn database_home(settings: &Settings, layout: &Layout, db: Database) -> Result<PathBuf> {
    let version = settings.database_version(db).ok_or_else(|| Error::msg(format!("{} is not installed", db.label())))?;
    Ok(layout.bin(db.id(), version))
}

/// The command-line client of a database (`mariadb` or `mysql`).
pub fn database_client(settings: &Settings, layout: &Layout, db: Database) -> Result<PathBuf> {
    let name = match db {
        Database::Mariadb => "mariadb",
        Database::Mysql => "mysql",
    };
    Ok(database_home(settings, layout, db)?.join("bin").join(exe(name)))
}

/// Client options for a database's tools: TCP to LampRabit's server as root. Unlike the
/// server's my.ini, this exists before the server has ever started.
pub fn write_client_config(settings: &Settings, layout: &Layout, db: Database) -> Result<PathBuf> {
    let etc = layout.etc(db.id());
    std::fs::create_dir_all(&etc)?;
    let file = etc.join("client.cnf");
    let conf = format!(
        "# Generated by LampRabit.\n[client]\nhost=127.0.0.1\nport={}\nuser=root\ndefault-character-set=utf8mb4\n",
        settings.database_port(db)
    );
    if std::fs::read_to_string(&file).ok().as_deref() != Some(conf.as_str()) {
        std::fs::write(&file, conf)?;
    }
    Ok(file)
}

pub fn mysql_home(settings: &Settings, layout: &Layout) -> Result<PathBuf> {
    let version = settings.versions.mysql.as_ref().ok_or_else(|| Error::msg("MySQL is not installed"))?;
    Ok(layout.bin("mysql", version))
}

/// MySQL can't be downgraded and upgrades in place are one-way, so each release line
/// (8.4, 9.7, 26.10…) keeps its own data folder and switching versions is always safe.
pub fn mysql_data(settings: &Settings, layout: &Layout) -> PathBuf {
    let line = settings.versions.mysql.as_deref().map(release_line).unwrap_or_default();
    layout.data(&format!("mysql-{}.{}", line.0, line.1))
}

pub fn write_mysql(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = mysql_home(settings, layout)?;
    let etc = layout.etc("mysql");
    std::fs::create_dir_all(&etc)?;
    let port = settings.ports.mysql_server;
    let bind = bind_addresses(settings.versions.mysql.as_deref().is_some_and(|v| release_line(v) >= (8, 0)));
    let socket = if cfg!(windows) {
        String::new()
    } else {
        format!("socket=\"{}\"\n", slash(&layout.tmp().join("mysqld.sock")))
    };
    // MySQL 8.4 ships native passwords off, but many PHP apps and tools still expect
    // them; 9.0 removed the plugin, so the option would stop newer versions starting.
    let native = if settings.versions.mysql.as_deref().is_some_and(|v| release_line(v).0 == 8) {
        "mysql_native_password=ON\n"
    } else {
        ""
    };
    let conf = format!(
        r#"# Generated by LampRabit. Changes are overwritten on every start.
[mysqld]
basedir="{home}"
datadir="{data}"
port={port}
bind-address={bind}
{socket}character-set-server=utf8mb4
collation-server=utf8mb4_0900_ai_ci
log-error="{logs}/mysql-error.log"
pid-file="{tmp}/mysqld.pid"
max_allowed_packet=64M
innodb_buffer_pool_size=256M
# The X Protocol port (33060) isn't needed for PHP and would clash between versions.
mysqlx=OFF
{native}
[client]
port={port}
{socket}default-character-set=utf8mb4
"#,
        home = slash(&home),
        data = slash(&mysql_data(settings, layout)),
        logs = slash(&layout.logs()),
        tmp = slash(&layout.tmp()),
    );
    std::fs::write(etc.join("my.ini"), conf)?;
    Ok(())
}

/// Linux: MySQL's generic builds link against two system libraries, libaio and libnuma.
/// Ubuntu 24.04+ and Debian 13 renamed libaio's file to libaio.so.1t64, which MySQL
/// doesn't find; a link under the old name goes in `lib/compat` of the MySQL folder.
/// Returns that folder for LD_LIBRARY_PATH, or an error naming the packages to install.
#[cfg(not(target_os = "linux"))]
pub fn mysql_libraries(_home: &Path) -> Result<Option<PathBuf>> {
    Ok(None)
}

#[cfg(target_os = "linux")]
pub fn mysql_libraries(home: &Path) -> Result<Option<PathBuf>> {
    let compat = home.join("lib").join("compat");
    let missing = || -> Vec<String> {
        let out = std::process::Command::new("ldd")
            .arg(home.join("bin").join("mysqld"))
            .env("LD_LIBRARY_PATH", &compat)
            .output();
        let text = out.map(|o| String::from_utf8_lossy(&o.stdout).into_owned()).unwrap_or_default();
        text.lines().filter(|l| l.contains("not found")).filter_map(|l| l.split_whitespace().next()).map(str::to_string).collect()
    };
    let mut gone = missing();
    if gone.iter().any(|l| l == "libaio.so.1") {
        let renamed = ["/usr/lib/x86_64-linux-gnu", "/lib/x86_64-linux-gnu", "/usr/lib/aarch64-linux-gnu", "/lib/aarch64-linux-gnu", "/usr/lib64", "/usr/lib"]
            .iter()
            .map(|d| Path::new(d).join("libaio.so.1t64"))
            .find(|p| p.exists());
        if let Some(target) = renamed {
            std::fs::create_dir_all(&compat)?;
            let link = compat.join("libaio.so.1");
            let _ = std::fs::remove_file(&link);
            std::os::unix::fs::symlink(target, &link)?;
            gone = missing();
        }
    }
    if gone.is_empty() {
        return Ok(compat.exists().then_some(compat));
    }
    Err(Error::msg(format!(
        "MySQL needs system libraries that aren't installed ({}). Install them, then start MySQL again: sudo apt install libaio1t64 libnuma1 (Ubuntu 24.04+, Debian 13), sudo apt install libaio1 libnuma1 (older Ubuntu/Debian), or sudo dnf install libaio numactl-libs (Fedora).",
        gone.join(", ")
    )))
}

/// Creates the system tables on first start of a release line. Root gets an empty
/// password, like MariaDB here (and XAMPP/Laragon).
pub async fn init_mysql_data(settings: &Settings, layout: &Layout) -> Result<()> {
    let data = mysql_data(settings, layout);
    if data.join("mysql.ibd").exists() || data.join("mysql").exists() {
        return Ok(());
    }
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        return Err(Error::msg(format!("{} is not empty but has no MySQL system tables; move it away to re-initialise", data.display())));
    }
    let home = mysql_home(settings, layout)?;
    let libs = mysql_libraries(&home)?;
    let mut cmd = tokio::process::Command::new(home.join("bin").join(exe("mysqld")));
    if let Some(dir) = libs {
        cmd.env("LD_LIBRARY_PATH", dir);
    }
    // mysqld creates the data folder itself and refuses one that already exists.
    cmd.arg(format!("--defaults-file={}", layout.etc("mysql").join("my.ini").display()))
        .arg("--initialize-insecure")
        .current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    if !out.status.success() {
        let _ = std::fs::remove_dir_all(&data);
        let log = std::fs::read_to_string(layout.logs().join("mysql-error.log")).unwrap_or_default();
        let reason = log.lines().rev().find(|l| l.contains("[ERROR]")).unwrap_or_default().to_string();
        return Err(Error::msg(format!(
            "MySQL data directory initialisation failed: {}{}{reason}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}

/// Nginx needs a writable prefix with logs/ and temp/ folders.
pub fn nginx_prefix(layout: &Layout) -> Result<PathBuf> {
    let prefix = layout.tmp().join("nginx");
    for dir in ["logs", "temp"] {
        std::fs::create_dir_all(prefix.join(dir))?;
    }
    Ok(prefix)
}
