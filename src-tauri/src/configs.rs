//! Generates service configs from settings. Files under `etc/` are rewritten before every
//! start, so they always match the active versions and ports.

use std::path::{Path, PathBuf};

use crate::{
    config::{Server, Settings},
    php::PoolPlan,
    error::{Error, Result},
    layout::{Layout, exe},
};

/// Paths in Apache/PHP/MariaDB configs use forward slashes on every OS.
fn slash(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

pub fn write_apache(settings: &Settings, layout: &Layout, plan: &[PoolPlan]) -> Result<()> {
    let version = settings.versions.apache.as_ref().ok_or_else(|| Error::msg("Apache is not installed"))?;
    let home = slash(&layout.bin("apache", version));
    let etc = layout.etc("apache");
    std::fs::create_dir_all(etc.join("sites"))?;
    let www = slash(&layout.www());
    let logs = slash(&layout.logs());
    let port = settings.server_ports(Server::Apache).0;
    let runtime_dir = layout.tmp().join("apache");
    std::fs::create_dir_all(&runtime_dir)?;

    let mut modules = vec![
        "access_compat", "actions", "alias", "allowmethods", "auth_basic", "authn_core", "authn_file",
        "authz_core", "authz_groupfile", "authz_host", "authz_user", "autoindex", "deflate", "dir", "env",
        "expires", "filter", "headers", "include", "lbmethod_byrequests", "log_config", "mime", "negotiation",
        "proxy", "proxy_balancer", "proxy_fcgi", "proxy_http", "rewrite", "setenvif", "slotmem_shm",
        "socache_shmcb", "vhost_alias",
    ];
    if !cfg!(windows) {
        modules.extend(["mpm_event", "unixd"]);
    }
    let modules: String = modules
        .iter()
        .map(|m| format!("LoadModule {m}_module modules/mod_{m}.so\n"))
        .collect();

    // PHP runs in FastCGI worker pools (see php.rs); one balancer per PHP version in use.
    let balancers: String = plan
        .iter()
        .map(|p| {
            let members: String = p.ports().map(|port| format!("    BalancerMember \"fcgi://127.0.0.1:{port}\"\n")).collect();
            format!("<Proxy \"balancer://{}/\">\n{members}</Proxy>\n", p.name())
        })
        .collect();
    let php = if plan.is_empty() {
        "# PHP is not installed\n".to_string()
    } else {
        // GENERIC passes SCRIPT_FILENAME as a plain path; on Windows it arrives as
        // "/C:/...", so strip the slash before the drive letter.
        format!(
            "ProxyFCGIBackendType GENERIC\nProxyFCGISetEnvIf \"reqenv('SCRIPT_FILENAME') =~ m#^/([A-Za-z]:/.*)#\" SCRIPT_FILENAME \"$1\"\n{balancers}{default}",
            default = crate::sites::apache_php_handler(crate::php::pool_for(plan, None, settings), ""),
        )
    };

    let conf = format!(
        r#"# Generated by lampRabit. Changes are overwritten on every start;
# put custom directives in etc/apache/sites/*.conf instead.

Define SRVROOT "{home}"
ServerRoot "${{SRVROOT}}"
Listen {port}
ServerName localhost:{port}
ServerAdmin admin@localhost

{modules}
<IfModule unixd_module>
    User daemon
    Group daemon
</IfModule>

<Directory />
    AllowOverride none
    Require all denied
</Directory>

DocumentRoot "{www}"
<Directory "{www}">
    Options Indexes FollowSymLinks
    AllowOverride All
    Require all granted
</Directory>

DirectoryIndex index.php index.html index.htm

<Files ".ht*">
    Require all denied
</Files>

DefaultRuntimeDir "{runtime}"
PidFile "{pidfile}"
ErrorLog "{logs}/apache-error.log"
LogLevel warn
LogFormat "%h %l %u %t \"%r\" %>s %b \"%{{Referer}}i\" \"%{{User-Agent}}i\"" combined
# lampRabit's own health checks would otherwise add a line every few seconds.
SetEnvIf User-Agent "^lampRabit/" lamprabit_probe
CustomLog "{logs}/apache-access.log" combined env=!lamprabit_probe

TypesConfig conf/mime.types
AddType application/x-compress .Z
AddType application/x-gzip .gz .tgz

<IfModule mpm_winnt_module>
    AcceptFilter http none
    AcceptFilter https none
    ThreadsPerChild 64
</IfModule>

EnableSendfile off
EnableMMAP off

{php}
# Virtual hosts for the folders in www/
Include "{vhosts}"
IncludeOptional "{sites}/*.conf"
"#,
        sites = slash(&etc.join("sites")),
        vhosts = slash(&crate::sites::config_path(layout, Server::Apache)),
        runtime = slash(&runtime_dir),
        pidfile = slash(&apache_pid_file(layout)),
    );
    std::fs::write(etc.join("httpd.conf"), conf)?;
    Ok(())
}

/// lampRabit stops Apache by ending its process tree, so a stale PID file is expected and
/// removed before each start rather than letting Apache warn about an unclean shutdown.
pub fn apache_pid_file(layout: &Layout) -> PathBuf {
    layout.tmp().join("httpd.pid")
}

/// Sends PHP's mail() to Mailpit. Windows PHP speaks SMTP itself; elsewhere mail() pipes
/// to a sendmail binary, and `mailpit sendmail` is a drop-in one.
fn mail_directives(settings: &Settings, layout: &Layout) -> String {
    let Some(version) = settings.versions.mailpit.as_ref().filter(|_| settings.route_mail) else {
        return String::new();
    };
    let port = settings.ports.mail_smtp;
    if cfg!(windows) {
        format!("\n; mail() goes to Mailpit\nSMTP = 127.0.0.1\nsmtp_port = {port}\nsendmail_from = \"lamprabit@localhost\"\n")
    } else {
        let mailpit = slash(&layout.bin("mailpit", version).join("mailpit"));
        format!("\n; mail() goes to Mailpit\nsendmail_path = \"{mailpit} sendmail -S 127.0.0.1:{port}\"\n")
    }
}

/// Glue files for the database tools: Adminer's login wrapper and phpMyAdmin's config.
pub fn write_tools(settings: &Settings, layout: &Layout) -> Result<()> {
    let db = format!("127.0.0.1:{}", settings.ports.mysql);
    if let Some(version) = &settings.versions.adminer {
        // Adminer refuses empty passwords by default; local root has none.
        let wrapper = format!(
            r#"<?php
// Generated by lampRabit. Lets the local root user (no password) log in and
// defaults the server to this environment's MariaDB.
function adminer_object() {{
    class LampRabitAdminer extends \Adminer\Adminer {{
        function login($login, $password) {{
            return true;
        }}
        function credentials() {{
            return array(\Adminer\SERVER !== '' ? \Adminer\SERVER : '{db}', $_GET['username'] ?? 'root', \Adminer\get_password());
        }}
    }}
    return new LampRabitAdminer;
}}
include __DIR__ . '/adminer.php';
"#
        );
        std::fs::write(layout.bin("adminer", version).join("index.php"), wrapper)?;
    }

    if let Some(version) = &settings.versions.phpmyadmin {
        let tmp = layout.tmp().join("phpmyadmin");
        std::fs::create_dir_all(&tmp)?;
        let config = format!(
            r#"<?php
// Generated by lampRabit; regenerated on every Apache start.
$cfg['blowfish_secret'] = '{secret}';
$i = 1;
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['port'] = '{port}';
$cfg['Servers'][$i]['auth_type'] = 'cookie';
$cfg['Servers'][$i]['AllowNoPassword'] = true;
$cfg['TempDir'] = '{tmp}';
$cfg['VersionCheck'] = false;
"#,
            secret = phpmyadmin_secret(layout)?,
            port = settings.ports.mysql,
            tmp = slash(&tmp),
        );
        let dir = layout.bin("phpmyadmin", version);
        std::fs::write(dir.join("config.inc.php"), config)?;
        // phpMyAdmin lags behind new PHP releases; keep deprecation notices off its pages.
        std::fs::write(dir.join(".user.ini"), "display_errors = Off\n")?;
    }
    Ok(())
}

/// phpMyAdmin encrypts its login cookie with this; kept stable so logins survive restarts.
fn phpmyadmin_secret(layout: &Layout) -> Result<String> {
    use std::hash::{BuildHasher, Hasher};
    let path = layout.etc("phpmyadmin").join("blowfish_secret");
    if let Ok(secret) = std::fs::read_to_string(&path) {
        if secret.trim().len() == 32 {
            return Ok(secret.trim().to_string());
        }
    }
    // RandomState is seeded from the OS RNG; two hashers give 32 hex characters.
    let secret: String = (0..2)
        .map(|_| format!("{:016x}", std::collections::hash_map::RandomState::new().build_hasher().finish()))
        .collect();
    std::fs::create_dir_all(path.parent().unwrap())?;
    std::fs::write(&path, &secret)?;
    Ok(secret)
}

/// Writes etc/php/<version>/php.ini (and php-fpm.conf outside Windows); returns the ini path.
pub fn write_php(settings: &Settings, layout: &Layout, version: &str, port: u16) -> Result<PathBuf> {
    let home = layout.bin("php", version);
    if !home.exists() {
        return Err(Error::msg(format!("PHP {version} is not installed")));
    }
    let etc = layout.etc("php").join(version);
    std::fs::create_dir_all(&etc)?;
    let sessions = layout.tmp().join("sessions");
    std::fs::create_dir_all(&sessions)?;

    // Start from PHP's own development defaults, then append overrides (later directives win).
    let mut ini = std::fs::read_to_string(home.join("php.ini-development")).unwrap_or_default();
    let ext_dir = home.join("ext");
    ini.push_str(&format!(
        r#"

; ---------------------------------------------------------------
; lampRabit overrides (regenerated on every start)
; ---------------------------------------------------------------
extension_dir = "{ext}"
memory_limit = 512M
upload_max_filesize = 128M
post_max_size = 128M
max_execution_time = 120
date.timezone = UTC
display_errors = On
log_errors = On
error_log = "{logs}/php-error.log"
session.save_path = "{sessions}"
upload_tmp_dir = "{tmp}"
"#,
        ext = slash(&ext_dir),
        logs = slash(&layout.logs()),
        sessions = slash(&sessions),
        tmp = slash(&layout.tmp()),
    ));

    let extensions = [
        "bz2", "curl", "exif", "fileinfo", "gd", "gettext", "intl", "mbstring", "mysqli", "openssl",
        "pdo_mysql", "pdo_sqlite", "sodium", "sqlite3", "xsl", "zip",
    ];
    for ext in extensions {
        if cfg!(windows) && !ext_dir.join(format!("php_{ext}.dll")).exists() {
            continue; // compiled in, or not shipped with this build
        }
        ini.push_str(&format!("extension={ext}\n"));
    }
    if !cfg!(windows) || ext_dir.join("php_opcache.dll").exists() {
        ini.push_str("zend_extension=opcache\nopcache.enable=1\nopcache.validate_timestamps=1\nopcache.revalidate_freq=0\n");
    }
    ini.push_str(&mail_directives(settings, layout));
    let ini_path = etc.join("php.ini");
    std::fs::write(&ini_path, ini)?;

    if !cfg!(windows) {
        let fpm = format!(
            "[global]\nerror_log = {logs}/php-fpm.log\n\n[www]\nlisten = 127.0.0.1:{port}\npm = dynamic\npm.max_children = 10\npm.start_servers = 2\npm.min_spare_servers = 1\npm.max_spare_servers = 4\n",
            logs = slash(&layout.logs()),
        );
        std::fs::write(etc.join("php-fpm.conf"), fpm)?;
    }
    Ok(ini_path)
}

pub fn mariadb_home(settings: &Settings, layout: &Layout) -> Result<PathBuf> {
    let version = settings.versions.mariadb.as_ref().ok_or_else(|| Error::msg("MariaDB is not installed"))?;
    Ok(layout.bin("mariadb", version))
}

pub fn write_mariadb(settings: &Settings, layout: &Layout) -> Result<()> {
    let home = mariadb_home(settings, layout)?;
    let etc = layout.etc("mariadb");
    std::fs::create_dir_all(&etc)?;
    let port = settings.ports.mysql;
    let socket = if cfg!(windows) {
        String::new()
    } else {
        format!("socket=\"{}\"\n", slash(&layout.tmp().join("mysql.sock")))
    };
    let conf = format!(
        r#"# Generated by lampRabit. Changes are overwritten on every start.
[mysqld]
basedir="{home}"
datadir="{data}"
port={port}
bind-address=127.0.0.1
{socket}character-set-server=utf8mb4
collation-server=utf8mb4_unicode_ci
log-error="{logs}/mariadb-error.log"
max_allowed_packet=64M
# Level 1 keeps real warnings but not "Aborted connection" notes from health checks.
log_warnings=1
innodb_buffer_pool_size=256M

[client]
port={port}
{socket}default-character-set=utf8mb4
"#,
        home = slash(&home),
        data = slash(&layout.data("mariadb")),
        logs = slash(&layout.logs()),
    );
    std::fs::write(etc.join("my.ini"), conf)?;
    Ok(())
}

/// Creates the system tables on first start. Root gets an empty password, like XAMPP/Laragon.
pub async fn init_mariadb_data(settings: &Settings, layout: &Layout) -> Result<()> {
    let data = layout.data("mariadb");
    if data.join("mysql").exists() {
        return Ok(());
    }
    if data.exists() && std::fs::read_dir(&data)?.next().is_some() {
        return Err(Error::msg(format!(
            "{} is not empty but has no MariaDB system tables; move it away to re-initialise",
            data.display()
        )));
    }
    std::fs::create_dir_all(&data)?;
    let home = mariadb_home(settings, layout)?;

    let mut cmd = if cfg!(windows) {
        let mut c = tokio::process::Command::new(home.join("bin").join(exe("mariadb-install-db")));
        c.arg(format!("--datadir={}", data.display()));
        c
    } else {
        let mut c = tokio::process::Command::new(home.join("scripts").join("mariadb-install-db"));
        c.args([
            "--no-defaults".to_string(),
            format!("--basedir={}", home.display()),
            format!("--datadir={}", data.display()),
            "--auth-root-authentication-method=normal".to_string(),
        ]);
        c
    };
    cmd.current_dir(&home);
    crate::procgroup::prepare(&mut cmd);
    let out = cmd.output().await?;
    if !out.status.success() {
        let _ = std::fs::remove_dir_all(&data);
        return Err(Error::msg(format!(
            "MariaDB data directory initialisation failed: {}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        )));
    }
    Ok(())
}

/// Nginx needs a writable prefix with logs/ and temp/ folders.
pub fn nginx_prefix(layout: &Layout) -> Result<PathBuf> {
    let prefix = layout.tmp().join("nginx");
    for dir in ["logs", "temp"] {
        std::fs::create_dir_all(prefix.join(dir))?;
    }
    Ok(prefix)
}
